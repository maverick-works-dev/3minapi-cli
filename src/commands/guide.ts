/**
 * guide — the instructions for an AI agent working in a 3minapi project. `init` writes the same text to AGENTS.md, so
 * the file always matches the CLI that wrote it and `guide` matches the CLI installed now.
 */
import {
	AGENTS_FILE,
	BIN,
	CLAUDE_FILE,
	CONTROL_DB_FILE,
	CREDENTIALS_FILE,
	DEFAULT_WORKERS_DIR,
	ExitCode,
	LOCAL_SERVER_TOKEN_FILE,
	PROJECT_CONFIG_FILE,
	PROJECT_RECORD_FILE,
	RESULT_TABLE_PREFIX,
	USER_DB_FILE,
	type Command
} from '../core/domain/index.ts';
import { DOTENV_FILE } from '../modules/workers/runtime/env.ts';
import { HANDLER_DOC, SETTINGS } from '../modules/workers/template.ts';

/** First line of a generated AGENTS.md. init replaces the file only while this line is there */
export const GENERATED_MARKER = `<!-- generated by ${BIN}`;

export function agentGuide(version: string): string {
	return `# ${BIN} project — guide for AI agents

This folder is a ${BIN} project. The user's machine runs as a 3Min API host: an AI creates tasks, and
\`${BIN} start\` fetches them and runs them with the worker files here. You help the user write, test and run
those workers. Every command below works from any folder and takes \`--json\` for machine-readable output.

## Edit

- **Worker files** — \`${DEFAULT_WORKERS_DIR}/<name>.mjs\` (or \`.mts\`, \`.js\`, \`.ts\`); one file is one worker.
  Start one with \`${BIN} worker new <name>\` (\`--ts\` for TypeScript) instead of writing it from scratch.
  \`${BIN} paths\` shows the workers folder if \`${PROJECT_CONFIG_FILE}\` moved it.
- **\`${DOTENV_FILE}\`** — secrets the workers read through \`ctx.env\`. Write the values the user gives you, but never
  print them back, log them or put them in a result.
- **\`${PROJECT_CONFIG_FILE}\`** — project settings. \`receiveMode\` is \`live\` (default) or \`poll\`; in poll mode
  \`pollIntervalMs\` sets how often \`start\` fetches, and every fetch is an API call counted against the quota.
- **\`package.json\`** — only when a worker needs a library. \`npm init -y\` writes \`"type": "commonjs"\`, which
  breaks \`.js\`/\`.ts\` workers that use \`export\`: keep workers as \`.mjs\`/\`.mts\`, or set \`"type": "module"\`.

## Run

| Command | Use |
|---|---|
| \`${BIN} worker run <name> --input '<json>'\` | Test a worker on this machine — no task, no API call (\`--input-file\` avoids shell quoting) |
| \`${BIN} worker list\` | Check that every worker file loads |
| \`${BIN} reload\` | After adding or renaming a worker, or changing a \`description\` — until then the AI sees the old one |
| \`${BIN} status\` | Whether \`start\` is running, its workers, the quota left |
| \`${BIN} logs\` / \`${BIN} worker logs <name>\` | The CLI's log / one worker's log |
| \`${BIN} worker results list\` / \`show <task_id>\` / \`query "<SQL>"\` | Results saved in \`${USER_DB_FILE}\` |
| \`${BIN} start --detach\` / \`${BIN} stop\` | Run the host in the background / stop it |
| \`${BIN} doctor\` | Check Node.js, config, network and proxy settings |
| \`${BIN} paths\` | Absolute paths of the files on this page |

Handler code and \`${DOTENV_FILE}\` edits apply to the next task with no reload. Ask the user before
\`${BIN} worker delete <name> --yes\` (it also deletes the worker and its task history on 3Min API) and before any
\`prune --yes\`.

## Do not touch

- **\`${CREDENTIALS_FILE}\`** (the host token) — never read, print or copy it. The user runs \`${BIN} login\` and types
  the token at its masked prompt; never ask for the token in the chat.
- **\`${CONTROL_DB_FILE}\`, \`runner.*\`, \`${PROJECT_RECORD_FILE}\`** — internal state. Use \`${BIN} tasks prune\` to clear history.
- **\`${LOCAL_SERVER_TOKEN_FILE}\`** — only for a local script that calls \`${BIN} start --serve\`.
- **Tables starting with \`${RESULT_TABLE_PREFIX}\` in \`${USER_DB_FILE}\`** — read them, never write them.

## Worker file

\`\`\`js
${SETTINGS}

${HANDLER_DOC}
export async function handler(input, ctx) {
	// ...
	return { ok: true };
}
\`\`\`

This text matches ${BIN} v${version}. Run \`${BIN} guide\` for the version installed now.
`;
}

/** AGENTS.md as init writes it — the marker line, then the guide */
export function agentsFileText(version: string): string {
	return (
		`${GENERATED_MARKER} v${version}. '${BIN} init' replaces this file while this line is here — ` +
		`delete the line to keep your own edits. -->\n\n${agentGuide(version)}`
	);
}

/** CLAUDE.md as init writes it — Claude Code imports AGENTS.md with `@` */
export const CLAUDE_FILE_TEXT = `@${AGENTS_FILE}\n`;

export const guide: Command = {
	name: 'guide',
	summary:
		'Print the guide for AI agents working in this project (also written to AGENTS.md by init)',
	usage: '',
	description:
		'Which files an AI agent edits, which commands it runs, which files it never touches, and how a\n' +
		`worker file is shaped. '${BIN} init' writes the same text to ${AGENTS_FILE}, plus a ${CLAUDE_FILE} that\n` +
		'imports it for Claude Code. No API call; works without a project.',
	options: {},
	args: { min: 0, max: 0 },
	async run(ctx) {
		const text = agentGuide(ctx.version);
		ctx.out.result({ version: ctx.version, guide: text }, text.trimEnd());
		return ExitCode.Ok;
	}
};
